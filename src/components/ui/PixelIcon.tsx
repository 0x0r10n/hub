export function PixelIcon({
  name,
  size = 12,
  className = "",
  color = "currentColor",
}: {
  name: keyof typeof PATTERNS;
  size?: number;
  className?: string;
  color?: string;
}) {
  const pattern = PATTERNS[name] ?? PATTERNS.dot;
  const cols = pattern[0]?.length ?? 8;
  const boxShadow = useMemo(() => {
    const px = size / cols;
    const shadows: string[] = [];
    pattern.forEach((row, y) => {
      row.split("").forEach((c, x) => {
        if (c === "1") {
          shadows.push(`${(x * px).toFixed(2)}px ${(y * px).toFixed(2)}px 0 0 ${color}`);
        }
      });
    });
    return shadows.join(", ");
  }, [pattern, size, cols, color]);

  const px = size / cols;

  return (
    <span
      aria-hidden
      className={`inline-block shrink-0 ${className}`}
      style={{
        width: px,
        height: px,
        boxShadow,
        transform: "translateZ(0)",
      }}
    />
  );
}

export type PixelIconName = keyof typeof PATTERNS;
